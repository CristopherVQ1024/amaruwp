CREATE TABLE IF NOT EXISTS `T_EMPRESAS` (
  `ID` int(11) NOT NULL AUTO_INCREMENT,
  `C_NOMBRE` varchar(150) NOT NULL,
  `C_DIRECCION` varchar(255) DEFAULT NULL,
  `C_DESCRIPCION` text DEFAULT NULL,
  `C_TIMEZONE` varchar(50) NOT NULL DEFAULT 'America/Lima',
  `F_STATUS` tinyint(1) NOT NULL DEFAULT 1,
  `D_CREATE` datetime DEFAULT current_timestamp(),
  `D_UPDATE` datetime DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  PRIMARY KEY (`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS `T_EMPRESAS_TELEFONOS` (
  `ID` int(11) NOT NULL AUTO_INCREMENT,
  `ID_EMPRESA` int(11) NOT NULL,
  `C_TELEFONO` varchar(30) NOT NULL,
  `D_CREATE` datetime DEFAULT current_timestamp(),
  PRIMARY KEY (`ID`),
  KEY `IDX_TEL_EMPRESA` (`ID_EMPRESA`),
  CONSTRAINT `FK_TEL_EMPRESA` FOREIGN KEY (`ID_EMPRESA`) REFERENCES `T_EMPRESAS` (`ID`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

